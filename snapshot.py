"""Validate portable dashboard exports before replacing the saved snapshot."""
import datetime as dt
import math
import re

from workflow import CLOSED_STAGE, OPPORTUNITY_TYPES, PARTNER_FIELD, SCOPE_VERSION, summary

MAX_UPLOAD_BYTES = 25 * 1024 * 1024
TEXT_FIELDS = ('name', 'account', 'accountOwner', 'stage', 'closeDate', 'type', 'segment', 'region',
               'partnerName', 'partnerOwnerName', 'partnerRepName', 'partnerRepSource', 'blockedReason', 'bucket', 'reason')
BOOL_FIELDS = ('partnerRepNeedsPopulate', 'partnerRepOnTeam', 'partnerRepOnSplit')


def validate_snapshot(value):
    if not isinstance(value, dict) or not isinstance(value.get('config'), dict):
        raise ValueError('Choose the pse-data.json file generated by the local Salesforce export command.')
    if value['config'].get('scopeVersion') != SCOPE_VERSION:
        raise ValueError('This file uses an older dashboard scope. Export fresh data using the current command.')
    generated = value.get('generatedAt')
    try:
        timestamp = dt.datetime.fromisoformat(generated.replace('Z', '+00:00'))
        if timestamp.tzinfo is None: raise ValueError()
    except (AttributeError, TypeError, ValueError):
        raise ValueError('The export must have a valid Salesforce extraction date with timezone.') from None
    if not isinstance(value.get('rows'), list):
        raise ValueError('The export must contain an Opportunity rows list.')
    rows, seen = [], set()
    for number, row in enumerate(value['rows'], 1):
        if not isinstance(row, dict): raise ValueError(f'Row {number} is not an Opportunity record.')
        opp_id = row.get('id')
        if not isinstance(opp_id, str) or not re.fullmatch(r'006[A-Za-z0-9]{12}(?:[A-Za-z0-9]{3})?', opp_id):
            raise ValueError(f'Row {number} has an invalid Opportunity ID.')
        if opp_id in seen: raise ValueError(f'Duplicate Opportunity ID at row {number}.')
        seen.add(opp_id)
        if (row.get('stage') != CLOSED_STAGE or row.get('type') not in OPPORTUNITY_TYPES
                or row.get('nonCommissionable') is not False or not row.get('partnerId')):
            raise ValueError(f'Row {number} is outside the closed, commissionable Opportunity scope with a Partner.')
        for field in BOOL_FIELDS:
            if type(row.get(field)) is not bool: raise ValueError(f'Row {number} is missing a valid {field} check.')
        if row.get('partnerRepActive') is not None and type(row['partnerRepActive']) is not bool:
            raise ValueError(f'Row {number} has an invalid PSE status.')
        clean = {'id': opp_id, 'nonCommissionable': False, **{field: row[field] for field in BOOL_FIELDS}}
        for field in TEXT_FIELDS:
            item = row.get(field)
            if item is not None and (not isinstance(item, str) or len(item) > 10000):
                raise ValueError(f'Row {number} has an invalid {field} value.')
            clean[field] = item
        try: dt.date.fromisoformat(row.get('closeDate'))
        except (TypeError, ValueError): raise ValueError(f'Row {number} has an invalid Close Date.') from None
        for field, prefix in (('partnerId', '001'), ('partnerRepId', '005')):
            item = row.get(field)
            if item is not None and (not isinstance(item, str) or not re.fullmatch(prefix + r'[A-Za-z0-9]{12}(?:[A-Za-z0-9]{3})?', item)):
                raise ValueError(f'Row {number} has an invalid {field}.')
            clean[field] = item
        amount = row.get('amount')
        if amount is not None and (type(amount) not in (int, float) or not math.isfinite(amount)):
            raise ValueError(f'Row {number} has an invalid amount.')
        clean.update(amount=amount, partnerRepActive=row.get('partnerRepActive'))
        rows.append(clean)
    return {'generatedAt': generated,
            'config': {'scopeVersion': SCOPE_VERSION, 'stage': CLOSED_STAGE, 'partnerField': PARTNER_FIELD,
                       'scope': 'Commissionable 08 - Closed Renewal, New Business, and Expansion opportunities',
                       'commissionableOnly': True, 'splitCheck': 'any', 'opportunityTypes': list(OPPORTUNITY_TYPES)},
            'rows': rows, 'summary': summary(rows)}
